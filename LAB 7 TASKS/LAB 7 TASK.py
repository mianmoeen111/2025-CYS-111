import ast

def minimax(tree):
    min_values = []

    for branch in tree:
        min_values.append(min(branch))

    best = max(min_values)
    return min_values, best


def alpha_beta(tree):
    alpha = float("-inf")
    checked = 0
    pruned = []

    branch_no = 0

    for branch in tree:
        branch_no = branch_no + 1
        beta = float("inf")

        for i in range(len(branch)):
            value = branch[i]
            checked = checked + 1

            if value < beta:
                beta = value

            if beta <= alpha:
                for j in range(i + 1, len(branch)):
                    pruned.append((branch_no, branch[j]))
                break

        if beta > alpha:
            alpha = beta

        print("Alpha after Branch", branch_no, ":", alpha)

    return alpha, checked, pruned


while True:
    user = input("\nEnter tree (or quit): ")

    if user.lower().strip() == "quit":
        print("Program stopped.")
        break

    try:
        tree = ast.literal_eval(user)

        if not isinstance(tree, list) or len(tree) == 0:
            print("Error: Enter a non-empty list.")
            continue

        valid = True

        for branch in tree:
            if not isinstance(branch, list) or len(branch) == 0:
                valid = False
                break

            for value in branch:
                if type(value) not in (int, float):
                    valid = False
                    break

        if not valid:
            print("Error: Every branch must contain numbers.")
            continue

        min_values, best = minimax(tree)
        best_branch = min_values.index(best) + 1

        total = 0
        for branch in tree:
            total = total + len(branch)

        ab_best, checked, pruned = alpha_beta(tree)

        saved = (total - checked) / total * 100

        print("\n--- FINAL RESULT ---")
        print("MIN values:", min_values)
        print("Minimax answer:", best)
        print("Alpha-Beta answer:", ab_best)
        print("Leaves checked (Minimax):", total)
        print("Leaves checked (Alpha-Beta):", checked)
        print("Leaves saved:", round(saved, 2), "%")
        print("Pruned leaves:", pruned)
        print("Best move for MAX: Branch", best_branch)

        if best == ab_best:
            print("Result: Both methods agree")
        else:
            print("Result: Answers are different")

    except (ValueError, SyntaxError, TypeError, OverflowError):
        print("Error: Invalid input. Please try again.")